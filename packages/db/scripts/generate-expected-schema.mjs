import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { is } from "drizzle-orm";
import { getTableConfig, SQLiteTable } from "drizzle-orm/sqlite-core";
import * as schema from "../dist/schema.js";

/**
 * Derived from the drizzle table objects, not from parsing the generated SQL.
 * Parsing SQL would be a second interpretation of the schema and could
 * disagree with drizzle's own; reading drizzle's metadata cannot.
 *
 * Types are upper-cased on both sides of the comparison because SQLite reports
 * whatever case the CREATE statement used, and that is not something worth
 * failing a deploy over.
 */
export function describe(table) {
	const config = getTableConfig(table);

	return {
		columns: config.columns.map((c) => ({
			name: c.name,
			type: c.getSQLType().toUpperCase(),
			notnull: c.notNull ? 1 : 0,
			pk: c.primary ? 1 : 0,
		})),
		indexes: config.indexes
			.map((i) => ({ name: i.config.name, unique: i.config.unique }))
			.sort((a, b) => a.name.localeCompare(b.name)),
	};
}

/**
 * Builds the expected-schema object from the built @onlooker/db schema module.
 *
 * Exported separately from the file write below so tests can compare a
 * freshly derived snapshot against the committed one without overwriting it
 * as a side effect of importing this module.
 *
 * is(v, SQLiteTable) rather than "_" in v: drizzle-orm moved table metadata
 * behind a symbol in 0.31, so the string key no longer matches - the same fix
 * applied in src/__tests__/schema.test.ts.
 */
export function generateExpectedSchema() {
	const expected = {};
	for (const value of Object.values(schema)) {
		if (is(value, SQLiteTable)) {
			expected[getTableConfig(value).name] = describe(value);
		}
	}
	return expected;
}

if (import.meta.url === `file://${process.argv[1]}`) {
	const expected = generateExpectedSchema();

	const here = dirname(fileURLToPath(import.meta.url));
	const packageRoot = resolve(here, "..");
	writeFileSync(
		resolve(packageRoot, "src/expected-schema.ts"),
		"// GENERATED by scripts/generate-expected-schema.mjs - do not edit.\n" +
			"// Regenerate with: pnpm --filter @onlooker/db generate:expected-schema\n" +
			`export const EXPECTED_SCHEMA = ${JSON.stringify(expected, null, "\t")} as const;\n`,
	);

	// JSON.stringify quotes every key and omits trailing commas; Biome wants
	// neither. Formatting here means the committed file always matches what
	// `pnpm --filter @onlooker/db lint` expects, rather than relying on
	// whoever regenerates it to remember a separate format step.
	execFileSync(
		"pnpm",
		["exec", "biome", "format", "--write", "src/expected-schema.ts"],
		{
			cwd: packageRoot,
			stdio: "inherit",
		},
	);

	console.log(
		`wrote src/expected-schema.ts (${Object.keys(expected).length} tables)`,
	);
}
